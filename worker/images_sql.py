#!/usr/bin/env python3
"""Turns crawl.json into SQL for public.images. Drops generic images (logos/icons, or the same picture on 3+ pages)."""
import json, re, sys, uuid, collections
from urllib.parse import urlparse
NS = uuid.UUID('6f1c2c0e-0b1e-4c53-9a47-5d2f2f7a1a10')
d = json.load(open(sys.argv[1]))['pages']
ok = {u: v for u, v in d.items() if v['status'] == 'ok'}
uses = collections.Counter(v['image'] for v in ok.values())
GENERIC = re.compile(r'logo|icon|favicon|apple-touch|placeholder|default|platzhalter|sprite|blank', re.I)
rows, dropped = [], collections.Counter()
for u, v in ok.items():
    img = v['image']
    if uses[img] >= 3: dropped['same image on 3+ pages'] += 1; continue
    if GENERIC.search(urlparse(img).path): dropped['logo/icon name'] += 1; continue
    if len(v['activities']) > 5: dropped['one page for 6+ listings'] += 1; continue
    for a in v['activities']: rows.append((a, img, u, urlparse(u).hostname))
q = lambda s: "'" + s.replace("'", "''") + "'"
out = ["-- Provider preview images (linked, not copied). Generated by worker/crawl_images.py + images_sql.py"]
for a, img, u, h in rows:
    i = uuid.uuid5(NS, f'{a}|{img}')
    out.append(f"insert into public.images (id, activity_id, image_url, source_url, credit, licence_status, note) values ('{i}', '{a}', {q(img)}, {q(u)}, {q(h)}, 'embedded_preview', 'og:image of the provider page; not licensed, linked only') on conflict do nothing;")
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(rows), 'rows;', dict(dropped), '; hosts:', collections.Counter(r[3] for r in rows).most_common(8))
