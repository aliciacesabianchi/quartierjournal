#!/usr/bin/env python3
"""Parks and public playgrounds from the City of Zurich's open data (Grün Stadt Zürich, Open Government Data).
Sources (WFS, GeoJSON): .../geoportal/Park (poi_park_view) and .../geoportal/POI_oeffentliche_Spielplaetze (poi_spielplatz_view).
Playgrounds within 120 m of a park are merged into that park's entry. Left out: playgrounds in paid pools ("in Badeanlage") and at community centres (we have them already).
Kreis from the coordinates (official quartier outlines). Usage: import_open_data_places.py parks.json playgrounds.json quartiere.json out.sql"""
import json, math, sys, uuid
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from kreis_geocode import inside
NS = uuid.UUID('6f1c2c0e-0b1e-4c53-9a47-5d2f2f7a1a55')
uid = lambda *p: str(uuid.uuid5(NS, ':'.join(map(str, p))))
def q(v):
    return 'null' if v is None else "'" + str(v).replace("'", "''") + "'"
def dist(a, b):
    la = math.radians((a[1] + b[1]) / 2); dx = (a[0] - b[0]) * 111320 * math.cos(la); dy = (a[1] - b[1]) * 110540
    return math.hypot(dx, dy)
def day(s):
    s = (s or '')[:8]
    return f'{s[:4]}-{s[4:6]}-{s[6:8]}' if len(s) == 8 and s.isdigit() else None
def quartier(pt, qs):
    for f in qs:
        g = f['geometry']; polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        if any(inside(pt, p[0]) for p in polys): return f['properties']['qname']
def clean(v): return (v or '').strip() or None
def play_text(p):
    bits = []
    if clean(p.get('eignung')): bits.append(f"Geeignet für {p['eignung'].strip()}")
    if clean(p.get('elemente')): bits.append(f"Elemente: {p['elemente'].strip()}")
    if clean(p.get('geraete')): bits.append(f"Geräte: {p['geraete'].strip()}")
    for k in ('besonderes', 'bemerkung'):
        if clean(p.get(k)): bits.append(p[k].strip())
    return ' · '.join(bits)

if __name__ == '__main__':
    parks = json.load(open(sys.argv[1]))['features']; plays = json.load(open(sys.argv[2]))['features']; qs = json.load(open(sys.argv[3]))['features']
    plays = [p for p in plays if (p['properties'].get('typ') or 'Spielplatz') == 'Spielplatz']
    E = ['-- Generated by worker/import_open_data_places.py. Source: Grün Stadt Zürich, Open Government Data (parks and public playgrounds). Safe to re-run.']
    merged = set(); n = {'park': 0, 'play': 0, 'merged': 0, 'outside': 0}
    for pk in parks:
        pp = pk['properties']; pt = tuple(pk['geometry']['coordinates'][:2]); qn = quartier(pt, qs)
        if not qn: n['outside'] += 1; continue
        feats = []
        if clean(pp.get('infrastruktur')): feats.append("Ausstattung: " + pp['infrastruktur'].strip().replace('_', ', '))
        for i, pl in enumerate(plays):
            if i not in merged and dist(pt, tuple(pl['geometry']['coordinates'][:2])) <= 120:
                merged.add(i); n['merged'] += 1; feats.append('Spielplatz: ' + play_text(pl['properties']))
        addr = ', '.join(x for x in [clean(pp.get('adresse')), (pp.get('plz') or '') + ' Zürich' if pp.get('plz') else None] if x)
        vid = uid('venue', 'park', pp.get('poi_id') or pp['objectid']); n['park'] += 1
        qsel = f"(select q.id from public.quartiers q join public.districts d on d.id = q.district_id where d.city_id = 'zurich' and q.name = {q(qn)})"
        E.append("insert into public.venues (id, name, kind, quartier_id, address, features, status, verification, data_origin, info_checked_on) values "
                 f"({q(vid)}, {q(pp['name'])}, 'Park', {qsel}, {q(addr or None)}, {q(' · '.join(feats) or None)}, 'published', 'provider_verified', 'open_data:stzh', {q(day(pp.get('datum')))}) on conflict (id) do nothing;")
    for i, pl in enumerate(plays):
        if i in merged: continue
        pp = pl['properties']; pt = tuple(pl['geometry']['coordinates'][:2]); qn = quartier(pt, qs)
        if not qn: n['outside'] += 1; continue
        addr = ', '.join(x for x in [clean(pp.get('adresse')), (pp.get('plz') or '') + ' Zürich' if pp.get('plz') else None] if x)
        vid = uid('venue', 'playground', pp.get('poi_id') or pp['objectid']); n['play'] += 1
        qsel = f"(select q.id from public.quartiers q join public.districts d on d.id = q.district_id where d.city_id = 'zurich' and q.name = {q(qn)})"
        name = pp['name'] if 'spielplatz' in pp['name'].lower() else f"Spielplatz {pp['name']}"
        E.append("insert into public.venues (id, name, kind, quartier_id, address, features, status, verification, data_origin, info_checked_on) values "
                 f"({q(vid)}, {q(name)}, 'Spielplatz', {qsel}, {q(addr or None)}, {q(play_text(pp) or None)}, 'published', 'provider_verified', 'open_data:stzh', {q(day(pp.get('datum')))}) on conflict (id) do nothing;")
    open(sys.argv[4], 'w', encoding='utf8').write('\n'.join(E) + '\n')
    print(n, file=sys.stderr)
