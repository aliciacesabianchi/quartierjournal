#!/usr/bin/env python3
"""Creates supabase/functions/_shared/taxonomy.ts from the app's src/domain/taxonomy.ts (same rules) plus the German labels
and short descriptions of every category, so the overview sheet classifies exactly like the website. Run after changing the taxonomy."""
import re
src = open('src/domain/taxonomy.ts', encoding='utf8').read()
src = src.replace("import type { ActivityCard } from './types'", "interface ActivityCard { title: string; category: string | null; image_url: string | null }")
labels = open('src/i18n/taxonomy.ts', encoding='utf8').read()
m = re.search(r"  de: \{ main: \{ (.*?) \}, sub: \{\n    (.*?) \}, other: '([^']*)'", labels, re.S)
pr = lambda t: dict(re.findall(r"(\w+): '((?:[^'\\]|\\.)*)'", t))
main, sub = pr(m.group(1)), pr(m.group(2))
DESC = {
 'baby': 'Treffen und Spiele für Babys und Kleinkinder mit Begleitperson (Krabbelgruppen, Babytreffs, Eltern-Kind-Gruppen).',
 'play': 'Freies und offenes Spielen: Spielplätze, Indoor-Spielplätze, offene Spielräume, Spielnachmittage.',
 'music': 'Singen, Musik und Konzerte: Eltern-Kind-Singen, Singkreise, Rhythmik, Konzerte für Familien.',
 'movement': 'Bewegung und Sport: Schwimmen, Turnen, Yoga, Tanz, Zirkus, Klettern, Eislaufen und mehr.',
 'creative': 'Basteln, Malen, Töpfern, Kochen und Backen mit Kindern.',
 'culture': 'Kunst, Geschichten und Theater: Vorlesen, Bibliotheken, Museen, Ausstellungen, Kino, Puppentheater.',
 'nature': 'Natur und Tiere: Wald, Spaziergänge, Parks, Gärtnern, Bauernhöfe, Zoo.',
 'festive': 'Feste und Feiern: Quartierfeste, Fasnacht, Räbeliechtli, Advent, Samichlaus, Märkte.',
 'shopping': 'Shopping und Secondhand: Kinderflohmärkte, Kleiderbörsen, Secondhand-Läden, Repair Cafés, Ludotheken.',
 'parents': 'Für Eltern und Betreuende: Austausch, Erziehung, Stillen, Schlaf, Erste Hilfe, Beratung.',
 'meetup': 'Cafés und Treffs: Familiencafés, Quartiertreffs, Frühstück, gemeinsames Mittagessen, Begegnungsgruppen.',
}
src += "\n// ── generated by worker/sync_function_taxonomy.py (do not edit) ──\n"
src += "export const LABEL_MAIN_DE: Record<string, string> = " + repr(main).replace("\\\\'", "\\'") + "\n"
src += "export const LABEL_SUB_DE: Record<string, string> = " + repr(sub).replace("\\\\'", "\\'") + "\n"
src += "export const DESCRIPTION_MAIN_DE: Record<string, string> = " + repr(DESC) + "\n"
open('supabase/functions/_shared/taxonomy.ts', 'w', encoding='utf8').write(src)
print('ok', len(main), 'main,', len(sub), 'sub labels')
